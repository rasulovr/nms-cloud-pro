import assert from 'node:assert/strict';
import {qrBuilderApplyOrder,qrBuilderMoveRow,qrBuilderTransferOrder,qrBuilderOverlay,qrBuilderLocalize,emptyQrBuilder} from '../src/qrMenuBuilder.mjs';
import {localizeBC4} from '../src/bc4MenuProjection.mjs';
const a={id:'a',category:'tea',categoryNames:{ru:'Чай',en:'Tea'},price:9.9,variants:[{cents:990}]};
const b={id:'b',category:'coffee',categoryNames:{ru:'Кофе',en:'Coffee'}};
const c={id:'c',category:'tea'};
const d={id:'d',category:'tea'};
const fixture=[a,b,c,d];
const ids=x=>x.map(p=>p.id);
assert.equal(qrBuilderApplyOrder(fixture,emptyQrBuilder()),fixture);
assert.deepEqual(ids(qrBuilderApplyOrder(fixture,{order:{tea:['c','b','c','missing','a']}})),['c','b','a','d']);
assert.deepEqual(ids(qrBuilderApplyOrder([d,a,c],{order:{tea:['a','c','d']}})),['a','c','d']);
assert.deepEqual(qrBuilderMoveRow(['a','b','c'],'a','c'),['b','c','a']);
assert.deepEqual(qrBuilderMoveRow(['a','b','c'],'c','a'),['c','a','b']);
assert.deepEqual(qrBuilderTransferOrder({tea:['a','c'],coffee:['b']},'a','tea','coffee'),{tea:['c'],coffee:['b','a']});
const fresh={kind:'new',category:'coffee',price_cents:875,copy:{names:{ru:'Новый напиток',en:'New drink'}}};
const docs={...emptyQrBuilder(),items:{a:{kind:'existing',category:'coffee',tags:['chef']},fresh}};
const moved=qrBuilderOverlay([a,b,c],docs,'BC5');
assert.equal(moved[0].category,'coffee');
assert.deepEqual(moved[0].categoryNames,b.categoryNames);
assert.equal(moved[0].variants[0].cents,990);
assert.equal(moved[0].price,9.9);
assert.equal(qrBuilderLocalize(moved[3],localizeBC4(moved[3],'en'),'en').name,'New drink');
assert.equal(moved[3].baseCents,875);
assert.deepEqual(qrBuilderOverlay([a,b,c],docs,'BC1').map(p=>p.id),['a','b','c']);
console.log('PASS category moves, translated category labels, category-only ordering in mixed views, legacy defaults, and newly created cart-only dishes');
