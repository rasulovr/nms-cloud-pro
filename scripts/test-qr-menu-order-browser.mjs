import assert from 'node:assert/strict';
import {createServer} from 'vite';
import {chromium} from 'playwright';
import {projectBC5} from '../src/bc5MenuProjection.mjs';
import {readFileSync} from 'node:fs';
import {emptyQrBuilder} from '../src/qrMenuBuilder.mjs';
process.env.VITE_SUPABASE_URL='https://qr-order-fixture.supabase.co';
process.env.VITE_SUPABASE_ANON_KEY='anonymous-test-key';
const html=(guest)=>`<meta charset="utf-8"><meta name="viewport" content="width=device-width"><div id="root"></div><script type="module">
  import React from '/node_modules/.vite/deps/react.js';
  import ReactDOM from '/node_modules/.vite/deps/react-dom_client.js';
  import View from '/src/${guest?'QRMenu':'QRMenuBuilderAdmin'}.jsx';
  ReactDOM.createRoot(document.getElementById('root')).render(React.createElement(View));
</script>`;
const vite=await createServer({appType:'custom',server:{host:'127.0.0.1',port:0,hmr:false},optimizeDeps:{include:['react','react-dom/client']},plugins:[{name:'qr-fixture',configureServer(server){
  server.middlewares.use(async(req,res,next)=>{const path=req.url.split('?')[0];if(!['/fixture-admin','/fixture-menu'].includes(path))return next();res.setHeader('Content-Type','text/html; charset=utf-8');res.end(await server.transformIndexHtml(req.url,html(path==='/fixture-menu')));});
}}]});
const rows=projectBC5(JSON.parse(readFileSync(new URL('../src/bc5InPlaceCatalogue.json',import.meta.url))));
let draft={revision:0,document:emptyQrBuilder()},live=null;
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
try{
 await vite.listen();
 const url='http://127.0.0.1:'+vite.httpServer.address().port;
 const context=await browser.newContext({locale:'ru-RU',viewport:{width:1220,height:920}});
 await context.route('https://qr-order-fixture.supabase.co/**',async route=>{
   const endpoint=new URL(route.request().url()).pathname.split('/').at(-1);
   let json=[];
   if(endpoint==='rms_qr_builder_save'){
     const q=route.request().postDataJSON();
     assert.equal(q.p_branch,'BC5');assert.equal(q.p_revision,draft.revision);
     draft={revision:draft.revision+1,document:q.p_document};
     if(q.p_publish)live=structuredClone(draft);
     json=draft.revision;
   }else if(endpoint==='rms_qr_builder_draft')json=draft.revision?[draft]:[];
   else if(endpoint==='rms_qr_builder_live')json=live?[live]:[];
   await route.fulfill({json,headers:{'access-control-allow-origin':'*'}});
 });
 await context.route('https://**/*',r=>r.request().url().startsWith('https://qr-order-fixture.supabase.co/')?r.fallback():r.abort());
 const page=await context.newPage();
 const issues=[];page.on('pageerror',e=>issues.push(e.message));
 await page.goto(url+'/fixture-admin');
 await page.getByRole('button',{name:'Категории',exact:true}).click();
 const pane=page.getByRole('region',{name:'Позиции в категории'});
 const head=rows.find(x=>rows.filter(y=>x.category===y.category).length>3);
 const baseline=rows.filter(x=>x.category===head.category);
 await pane.locator('select').selectOption(head.category);
 const list=()=>pane.locator('.qb-order-name b').allTextContents();
 assert.equal((await list())[0],baseline[0].name);
 const li=pane.locator('li');
 await li.nth(0).locator('.qb-order-grip').dragTo(li.nth(2));
 assert.equal((await list())[2],baseline[0].name);
 await pane.getByRole('button',{name:'Сохранить порядок в черновик'}).click();
 await page.getByText('Черновик сохранён.',{exact:true}).waitFor();
 assert.deepEqual(draft.document.order[head.category].slice(0,3),[baseline[1].id,baseline[2].id,baseline[0].id]);
 await page.locator('.qb-languages input').first().fill('Тестовая категория');
 await page.getByRole('button',{name:'Сохранить в черновик',exact:true}).click();
 await pane.getByText('Тестовая категория · 0').waitFor();
 const newCat=Object.keys(draft.document.categories)[0];
 await pane.locator('select').selectOption(head.category);
 await li.nth(2).getByRole('button',{name:'Редактировать'}).click();
 const item=page.locator('form.qb-form');
 assert.equal(await item.getByLabel('Категория').inputValue(),head.category);
 const marks=item.locator('.qb-tag-option .qr-paper-tag');
 const widths=await marks.evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().width));
 assert.equal(widths.length,4);assert.equal(new Set(widths).size,1);
 await item.getByRole('checkbox',{name:'Chef’s Choice'}).check();
 await item.getByLabel('Категория').selectOption(newCat);
 await item.getByRole('button',{name:'Сохранить в черновик'}).click();
 await page.getByText('Черновик сохранён.',{exact:true}).waitFor();
 assert.equal(draft.document.items[baseline[0].id].category,newCat);
 assert.equal(draft.document.order[head.category].includes(baseline[0].id),false);
 assert.deepEqual(draft.document.items[baseline[0].id].tags,['chef']);
 assert.equal(live,null);
 const guest=await context.newPage();guest.on('pageerror',e=>issues.push(e.message));
 await guest.goto(url+'/fixture-menu?branch=BC5');
 const cards=guest.locator('.product-card');
 await cards.first().waitFor();
 assert.equal(await cards.count(),184);
 await page.getByRole('button',{name:'Опубликовать BC5'}).click();
 await page.getByText('Меню BC5 опубликовано.').waitFor();
 await guest.reload();
 await guest.getByRole('button',{name:'Тестовая категория',exact:true}).click();
 assert.equal(await cards.count(),1);
 assert.match(await cards.first().innerText(),/Chef’s Choice/i);
 const after=await cards.first().locator('h3').textContent();
 assert.equal(after.toLocaleLowerCase('ru'),baseline[0].name.toLocaleLowerCase('ru'));
 await guest.getByRole('button',{name:new RegExp(head.categoryNames.ru,"iu")}).click();
 const products=await cards.locator('h3').allTextContents();
 assert.deepEqual(products.slice(0,2).map(x=>x.toLocaleLowerCase('ru')),[baseline[1].name.toLocaleLowerCase('ru'),baseline[2].name.toLocaleLowerCase('ru')]);
 assert.deepEqual(issues,[]);
 console.log('PASS real builder & QR components: same-size tags, drag, category creation and move, save/publish isolation, published chapter order, no runtime errors');
}finally{await browser.close();await vite.close();}
